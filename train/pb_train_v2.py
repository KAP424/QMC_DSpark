warmup_steps = int(a.warmup * total_steps)


def lr_lambda(step):                                    # official CosineAnnealingWarmupLR, eta_min=0
    if step < warmup_steps:
        return (step + 1) / max(1, warmup_steps)
    p_ = (step - warmup_steps) / max(1, total_steps - warmup_steps)
    return 0.5 * (1.0 + math.cos(math.pi * p_))


sched = torch.optim.lr_scheduler.LambdaLR(opt, lr_lambda)
DECAY = torch.exp(-torch.arange(N_DRAFT, device=DEV, dtype=torch.float32) / a.gamma)  # w_k, k=0..N_DRAFT-1


def v2_loss(feats, toks, o, p_t):
    '''Official loss: weighted mean per term, weights exp(-(k-1)/gamma).'''
    with torch.autocast('cuda', torch.bfloat16):
        hctx = d.encode_ctx(feats)
        z = d.backbone(hctx, d.embed(toks[..., 0]), o)
        prev = toks[..., :N_DRAFT]
        lg = d.logits(z, prev).float()
        cl = d.confidence(z, prev).float()
    logq = torch.log_softmax(lg, -1)
    ce = -logq.gather(-1, toks[..., 1:].unsqueeze(-1)).squeeze(-1)
    tv = (logq.exp() - p_t).abs().sum(-1)               # L1 = 2*TV, official l1_dist_per_token
    alpha = 1.0 - 0.5 * tv.detach()
    bce = F.binary_cross_entropy_with_logits(cl, alpha, reduction='none')
    den = DECAY.sum()
    ce_m = (ce * DECAY).sum() / den
    l1_m = (tv * DECAY).sum() / den
    bce_m = (bce * DECAY).sum() / den
    loss = W_CE * ce_m + W_L1 * l1_m + W_CONF * bce_m
    with torch.no_grad():
        m = lambda t: t.float().mean((0, 1))
        st = dict(ce=ce_m, l1=l1_m, bce=bce_m, alpha=m(alpha),
                  hit=m(logq.argmax(-1) == p_t.argmax(-1)))
    return loss, st


@torch.no_grad()
def eval_tau(seqs_, temp=1.0, A=8, bs=16, seed=123):
    '''tau from per-slot alpha (needs the full alpha vector, not its mean).'''
    was = d.training
    d.eval()
    g = torch.Generator().manual_seed(seed)
    al, n = None, 0
    for b0 in range(0, len(seqs_), bs):
        feats, toks, o, p_t = make_blocks(model, EOS, seqs_[b0:b0 + bs], A, g, temp, DEV)
        if feats is None:
            continue
        with torch.autocast('cuda', torch.bfloat16):
            hctx = d.encode_ctx(feats)
            z = d.backbone(hctx, d.embed(toks[..., 0]), o)
            lg = d.logits(z, toks[..., :N_DRAFT]).float()
        q = torch.softmax(lg, -1)
        al_k = torch.minimum(p_t, q).sum(-1).mean((0, 1)).cpu()      # (7,)
        al = al_k if al is None else al + al_k
        n += 1
    d.train(was)
    al = (al / n).tolist() if n > 0 else [0.0] * N_DRAFT
    en = sum(torch.cumprod(torch.tensor(al), 0))                     # E[n] = sum_k prod_{j<=k} alpha_j
    return dict(tau=float(en) + 1.0, alpha=[round(x, 3) for x in al])


