'''DSpark drafter training v2 — aligned with the official DeepSpec recipe (dspark_qwen3_4b).

Changes vs the first pb_train.py run, each verified against the official source:
  1. Data: responses regenerated by the target at the recommended sampling parameters
     T=0.7 / top_p=0.8 / top_k=20 (gen07/), max_new 1024. Loss and evaluation stay at T=1.0
     (official: softmax of cached target logits, no temperature; eval temperature 1.0).
  2. Loss decay gamma=4.0 (official loss_decay_gamma), w_k = exp(-(k-1)/4).
  3. Each loss term is a weighted mean (num/den over the weight mask), not a raw sum.
     loss = 0.1*CE + 0.9*L1 + 1.0*BCE. L1 term is sum |p-q| (= 2*TV), same as official.
  4. AdamW lr 6e-4, weight_decay 0, linear warmup 4% then cosine to 0, grad clip 1.0.
  5. Drafter forward/backward in bf16 autocast (fp32 master params, official BF16Optimizer style).
  6. Many anchors per sequence (default 32; official 512) — the measured dominant factor.
  7. Target is recomputed per step (official precomputes a cache; not needed at this scale).

Target stays frozen: parameters loaded read-only, requires_grad_(False); drafter params live in a
separate module. Checkpoints go to a NEW directory, nothing under parameter/draft/dspark_pb is touched.
'''
