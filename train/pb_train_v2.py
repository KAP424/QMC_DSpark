def do_eval(step):
    global best
    e1 = eval_tau(val_paper, 1.0)
    e2 = eval_tau(val_indist, 1.0)
    rec = {'step': step, 'tau_paper': e1['tau'], 'alpha_paper': e1['alpha'],
           'tau_indist': e2['tau'], 'lr': sched.get_last_lr()[0],
           'sec_per_step': round((time.time() - t0) / max(1, step - start_step), 3),
           'peak_gb': round(torch.cuda.max_memory_allocated() / 1e9, 1)}
    print(f"step {step:6d}  tau_paper {e1['tau']:.3f}  tau_indist {e2['tau']:.3f}  "
          f"alpha {' '.join(f'{x:.2f}' for x in e1['alpha'])}  lr {rec['lr']:.2e}", flush=True)
    logf.write(json.dumps(rec) + '\n')
    logf.flush()
    if e1['tau'] > best:
        best = e1['tau']
        torch.save({'model': d.state_dict(), 'step': step, 'tau': best}, f'{a.out}/best.pt')
    s = {'model': d.state_dict(), 'opt': opt.state_dict(), 'sched': sched.state_dict(),
         'step': step, 'best': best}
    torch.save(s, ckpt + '.tmp')
    os.replace(ckpt + '.tmp', ckpt)


